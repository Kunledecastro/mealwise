#!/usr/bin/env python3
"""
Builds catalogue/ingredients.generated.ts from the official source tables, so that no
nutrition figure in Mealwise is typed by hand.

Sources (download them yourself; they are not stored in the repo):
  - FAO/INFOODS Food Composition Table for Western Africa (2019), WAFCT_2019.xlsx
    https://www.fao.org/fileadmin/user_upload/faoweb/2020/WAFCT_2019.xlsx
    Sheet "03 NV_sum_39 (per 100g EP)". Values in [brackets] are estimates in the source;
    we use the number and keep the flag.
  - USDA FoodData Central, SR Legacy (public domain, CC0), via the FDC API.
    Needs an API key in the environment variable FDC_API_KEY (never commit it).
    USDA "carbohydrate by difference" includes fibre; we subtract fibre so all carbs are
    "available carbohydrate" like WAFCT.

Usage:
  FDC_API_KEY=... python3 scripts/catalogue/build_ingredients.py path/to/WAFCT_2019.xlsx
"""
import json
import os
import sys
import urllib.request

import openpyxl

from ingredient_spec import SPEC  # ids, names, groups, allergens and source codes (hand-maintained)


def wafct_table(path):
    wb = openpyxl.load_workbook(path, read_only=True, data_only=True)
    ws = wb["03 NV_sum_39 (per 100g EP)"]
    out = {}
    for r in ws.iter_rows(min_row=4, values_only=True):
        if not r[0] or not r[1]:
            continue

        def num(v):
            if v is None or str(v).strip() in ("", "-"):
                return None, False
            s = str(v).strip()
            if s.strip("[]").lower() == "tr":  # "trace" in food tables: present in negligible amount
                return 0.0, True
            return float(s.strip("[]").replace(",", ".")), s.startswith("[")

        vals = {k: num(r[i]) for k, i in (("kcal", 7), ("protein", 9), ("fat", 10), ("carbs", 11), ("fibre", 12))}
        out[str(r[0])] = {"name": r[1], "vals": vals}
    return out


def usda_food(fdc_id, key):
    req = urllib.request.Request(
        f"https://api.nal.usda.gov/fdc/v1/food/{fdc_id}?format=abridged&nutrients=208,203,204,205,291",
        headers={"X-Api-Key": key},
    )
    with urllib.request.urlopen(req, timeout=60) as resp:
        d = json.load(resp)
    v = {}
    for n in d["foodNutrients"]:
        num = str(n.get("number") or n.get("nutrientNumber"))
        v[num] = n.get("amount", n.get("value"))
    fibre = v.get("291") or 0.0
    return {
        "name": d["description"],
        "vals": {
            "kcal": (v["208"], False),
            "protein": (v["203"], False),
            "fat": (v["204"], False),
            "carbs": (round(v["205"] - fibre, 2), False),
            "fibre": (fibre, False),
        },
    }


def ts(v):
    return json.dumps(v, ensure_ascii=False)


def main():
    wafct = wafct_table(sys.argv[1])
    key = os.environ.get("FDC_API_KEY", "")
    lines = [
        "// GENERATED by scripts/catalogue/build_ingredients.py — do not edit numbers by hand.",
        "// Edit scripts/catalogue/ingredient_spec.py (names, groups, allergens, source codes) and re-run.",
        'import type { IngredientDef } from "./types";',
        "",
        "export const GENERATED_INGREDIENTS: IngredientDef[] = [",
    ]
    for s in SPEC:
        if s["source"] == "wafct":
            food = wafct[s["ref"]]
        else:
            if not key:
                sys.exit("FDC_API_KEY is required for USDA ingredients")
            food = usda_food(s["ref"], key)
        vals = food["vals"]
        missing = [k for k, (n, _) in vals.items() if n is None]
        if missing:
            # Missing fibre in a source is treated as 0 only if the spec says so explicitly.
            if missing == ["fibre"] and s.get("fibreZeroIfMissing"):
                vals["fibre"] = (0.0, True)
            else:
                sys.exit(f"{s['id']}: source {s['ref']} has no value for {missing}")
        per = {k: round(n, 2) for k, (n, _) in vals.items()}
        estimated = [k for k, (_, est) in vals.items() if est]
        entry = {
            "id": s["id"],
            "name": s["name"],
            "group": s["group"],
            "per100g": per,
            "nutrition": {
                "sourceId": s["source"],
                "ref": str(s["ref"]),
                "sourceName": food["name"],
            },
            "contains": s.get("contains", []),
            "allergenStatus": s.get("allergenStatus", "known"),
        }
        if s.get("aliases"):
            entry["aliases"] = s["aliases"]
        if s.get("mayContain"):
            entry["mayContain"] = s["mayContain"]
        if s.get("substitute"):
            entry["nutrition"]["substituteNote"] = s["substitute"]
        if estimated:
            entry["nutrition"]["estimatedInSource"] = estimated
        lines.append(f"  {ts(entry)},")
    lines.append("];")
    out = os.path.join(os.path.dirname(__file__), "..", "..", "catalogue", "ingredients.generated.ts")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Wrote {len(SPEC)} ingredients to {os.path.normpath(out)}")


if __name__ == "__main__":
    main()
