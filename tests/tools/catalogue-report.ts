import { writeFileSync } from "node:fs";
import { it } from "vitest";
import { CATALOGUE_VERSION, INGREDIENTS, MEALS } from "@/catalogue";
import { NUTRITION_SOURCES } from "@/catalogue/sources";
import { MEAL_TYPE_LABEL } from "@/lib/types";

// Writes docs/CATALOGUE_REVIEW.md: everything the product owner needs to review a catalogue batch.
it("writes the catalogue review document", () => {
  const src = new Map(NUTRITION_SOURCES.map((s) => [s.id, s.shortName]));
  const L: string[] = [];
  L.push(`# Mealwise — Catalogue review (edition ${CATALOGUE_VERSION})`, "");
  L.push("GENERATED by `npm run catalogue:report` from the catalogue files. Do not edit by hand.", "");
  L.push("All figures are per serving and are **estimates** calculated from ingredient weights × published food-composition values.", "");
  L.push("## How to review", "");
  L.push("For each meal, check: is the **serving size** realistic? Are the **ingredient amounts** (especially oil) how you'd cook it? Is anything missing? Note the slug and what to change.", "");
  L.push("## Summary", "");
  L.push("| Meal | Slots | kcal | Protein g | Carbs g | Fat g | Fibre g | Diet | Allergens (contains / may contain) |", "|---|---|---|---|---|---|---|---|---|");
  for (const m of MEALS) {
    const diet = (m.diets ?? []).filter((d) => ["Vegan", "Vegetarian", "Pescatarian"].includes(d))[0] ?? "Contains meat";
    L.push(`| ${m.name} (\`${m.slug}\`) | ${m.mealTypes.map((t) => MEAL_TYPE_LABEL[t]).join(", ")} | ${m.kcal} | ${Math.round(m.protein)} | ${Math.round(m.carbs)} | ${Math.round(m.fat)} | ${Math.round(m.fibre ?? 0)} | ${diet} | ${m.allergens.join(", ") || "—"} / ${(m.mayContain ?? []).join(", ") || "—"} |`);
  }
  L.push("", "## Meals in detail", "");
  for (const m of MEALS) {
    L.push(`### ${m.name}`, "", `${m.description} Serving: ${m.serving}. Time: ${m.prepMinutes} min. Cuisine: ${m.cuisine}.`, "");
    L.push("| Ingredient | Amount | g | Counted |", "|---|---|---|---|");
    for (const i of m.ingredients) L.push(`| ${i.name} | ${i.quantity} | ${i.grams} | ${i.optional ? "no (optional)" : "yes"} |`);
    L.push("", "Assumptions: " + (m.assumptions ?? []).join(" "), "");
    if (m.substitutes?.length) L.push("Close matches: " + m.substitutes.join(" "), "");
  }
  L.push("## Ingredients and sources", "");
  L.push("| Ingredient | Source | Code | Source food | kcal/100 g | Note |", "|---|---|---|---|---|---|");
  for (const i of INGREDIENTS)
    L.push(`| ${i.name} | ${src.get(i.nutrition.sourceId)} | ${i.nutrition.ref} | ${i.nutrition.sourceName} | ${i.per100g.kcal} | ${[i.nutrition.substituteNote, i.nutrition.estimatedInSource?.length ? `Source marks ${i.nutrition.estimatedInSource.join(", ")} as estimated.` : ""].filter(Boolean).join(" ")} |`);
  writeFileSync("docs/CATALOGUE_REVIEW.md", L.join("\n") + "\n");
});
